#!/usr/bin/env python3
"""Embed mods/wifisync/wifisync_ap.sh as a C string literal header.

The .sh file is the single source of truth (checked with `sh -n`); the mod
build regenerates the header, so the embedded fallback can never drift from
the file a user can copy to E:\\mods\\wifisync_ap.sh.
"""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def c_escape(text: str) -> str:
    out = []
    for line in text.splitlines(keepends=True):
        esc = (
            line.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\t", "\\t")
            .replace("\r", "")
            .replace("\n", "\\n")
        )
        out.append(f'    "{esc}"\n')
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--in", dest="src", type=Path,
                    default=ROOT / "mods/wifisync/wifisync_ap.sh")
    ap.add_argument("--out", dest="dst", type=Path,
                    default=ROOT / "artifacts/tests/wifisync-build/wifisync_ap_script.h")
    ap.add_argument("--symbol", default="ws_ap_script")
    a = ap.parse_args()
    text = a.src.read_text(encoding="utf-8")
    body = c_escape(text)
    a.dst.parent.mkdir(parents=True, exist_ok=True)
    a.dst.write_text(
        "/* Generated by tools/research/wifisync_embed.py from "
        f"{a.src.name}; do not edit. */\n"
        f"static const char {a.symbol}[] =\n{body};\n",
        encoding="utf-8",
    )
    print(f"embedded {a.src.name} ({len(text)} bytes) -> {a.dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
