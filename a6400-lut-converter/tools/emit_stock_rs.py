"""Emit the Rust constants for the hash-verified ILCE-6400 2.00 av-cam.bin stock tables.

The preset container already carries stock tables per file; these constants are the provenance
anchor used by `bionz-preset` tests to prove that shipped presets carry the genuine av-cam bytes
(EC_REC28_V1, FC_TBL0, STOCK_A0/A1/B2), never a synthetic ramp.

Usage (from the repository root):
    python a6400-lut-converter/tools/emit_stock_rs.py
"""
from __future__ import annotations

import hashlib
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from mods.film_sims.studio_core import STOCK_A0, STOCK_A1, STOCK_B2, get_target  # noqa: E402

OUT = ROOT / "isp-studio/crates/bionz-preset/src/stock_a6400.rs"
EXPECTED_SHA256 = "dd8f8d0cc74ad4b70100e5728cf8b159b5155e7fb50eaf1147b99c9054740209"


def fmt(values, dtype: str) -> str:
    body = ", ".join(str(int(v)) for v in values)
    return f"[{body}]"


def main() -> None:
    profile = get_target("a6400")
    av = profile.avcam_default_path.read_bytes()
    sha = hashlib.sha256(av).hexdigest()
    if sha != EXPECTED_SHA256:
        raise SystemExit(f"av-cam.bin hash mismatch: {sha}")
    ec_off = profile.ec_gamma_pa - 0x035C6000
    fc_off = profile.fc_gamma_pa - 0x035C6000
    ec = list(struct.unpack_from("<96I", av, ec_off))
    fc = list(struct.unpack_from("<96H", av, fc_off))
    text = "\n".join(
        [
            "//! Generated by `a6400-lut-converter/tools/emit_stock_rs.py` from the ILCE-6400 2.00",
            "//! `av-cam.bin`. Do not edit by hand.",
            "",
            f'pub const AVCAM_SHA256: &str = "{sha}";',
            "",
            "/// Still EC table `EC_REC28_V1` (96 x uint32, 10-bit code << 6).",
            f"pub const EC_REC28_V1: [u32; 96] = {fmt(ec, 'u32')};",
            "",
            "/// Still FC table `FC_TBL0` (96 x uint16, 0..1023).",
            f"pub const FC_TBL0: [u16; 96] = {fmt(fc, 'u16')};",
            "",
            "/// Published stock Q10 colour matrices (the Color Mode A0/A1/B2 rows).",
            f"pub const STOCK_A0: [i16; 9] = {fmt(STOCK_A0, 'i16')};",
            f"pub const STOCK_A1: [i16; 9] = {fmt(STOCK_A1, 'i16')};",
            f"pub const STOCK_B2: [i16; 9] = {fmt(STOCK_B2, 'i16')};",
            "",
            "/// 32-byte digest exactly as stored in a BZLK `avcam_sha256` field.",
            "pub fn avcam_sha256_bytes() -> [u8; 32] {",
            "    let mut out = [0u8; 32];",
            "    for (i, byte) in out.iter_mut().enumerate() {",
            '        *byte = u8::from_str_radix(&AVCAM_SHA256[i * 2..i * 2 + 2], 16).expect("hex digest");',
            "    }",
            "    out",
            "}",
            "",
        ]
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({sha})")


if __name__ == "__main__":
    main()
