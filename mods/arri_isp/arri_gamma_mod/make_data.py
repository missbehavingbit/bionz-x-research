"""Emit the stock and ARRI curve words for record 31 as a C header (offline)."""
import hashlib, struct, sys
from pathlib import Path
root = Path(__file__).resolve().parents[3]
d = root / "artifacts/analysis/arri-gamma-test-block-2026-11-16"
SHA = {"record31-stock.bin": "bc1d67e362549d6fda06c48e86fff4648cb099819e38d6e16032b0be99ceed58",
       "record31-arri-classic-rec709.bin": "93d69d065c0547abdf680bc104a80780360111b2e312163e99a74f34659de744",
       "record31-arri-logc3-awg3.bin": "d2accfa1fc39e37d7e987f1211c4411010e1eb965feb283f5d3764078c9539e6"}
preset = {"classic": "record31-arri-classic-rec709.bin", "logc3": "record31-arri-logc3-awg3.bin"}[sys.argv[1]]
words = {}
for name in ("record31-stock.bin", preset):
    b = (d / name).read_bytes()
    assert hashlib.sha256(b).hexdigest() == SHA[name], name
    words[name] = struct.unpack("<105I", b)
assert words["record31-stock.bin"][96:] == words[preset][96:]
fmt = lambda w: ",".join(hex(x) for x in w[:96])
Path(sys.argv[2]).write_text(
    "/* Generated by make_data.py from hash-checked record-31 blocks. */\n#include <stdint.h>\n"
    f"static const uint32_t ARRI_STOCK[96] = {{{fmt(words['record31-stock.bin'])}}};\n"
    f"static const uint32_t ARRI_NEW[96] = {{{fmt(words[preset])}}};\n")
