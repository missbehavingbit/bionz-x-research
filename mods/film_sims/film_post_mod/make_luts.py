#!/usr/bin/env python3
"""Generate pre-baked uint8_t[256] LUT header `film_post_luts.h` for FilmPost.mod.

Zero runtime floats or math.h calls are needed on the camera.
"""
from __future__ import annotations

import math
from pathlib import Path

OUT = Path(__file__).resolve().parent / "film_post_luts.h"

HALATION_PRESETS = [
    # (name, low, high, local_diff, global_diff, scattering, amp, defringe, impact)
    ("35mm (Default)",   0.15, 0.80, 0.15, 0.25, 0.60,  1.0, 1.00, 0.54),
    ("35mm No Remjet",   0.00, 0.80, 0.25, 0.35, 0.68,  1.0, 1.00, 0.80),
    ("16mm",             0.15, 0.80, 0.20, 0.35, 0.595, 1.0, 0.00, 0.80),
    ("8mm No Remjet",    0.00, 0.80, 0.45, 0.75, 0.68,  1.0, 1.00, 0.80),
]

GRAIN_PRESETS = [
    # (name, amount, scale, shadows, midtones, highlights, color)
    ("35mm ISO 250", 0.20,  1.0, 0.30, 0.55, 0.65, 0.65),
    ("35mm ISO 500", 0.40, 16.0, 0.35, 0.55, 0.65, 0.70),
    ("16mm ISO 250", 0.45, 25.0, 0.30, 0.55, 0.65, 0.65),
    ("8mm ISO 500",  0.70, 48.0, 0.30, 0.45, 0.65, 0.90),
]


def to_u8(v: float) -> int:
    return max(0, min(255, int(round(max(0.0, min(1.0, v)) * 255.0))))


def smoothstep(edge0: float, edge1: float, x: float) -> float:
    if edge1 <= edge0:
        return 1.0 if x >= edge1 else 0.0
    t = max(0.0, min(1.0, (x - edge0) / (edge1 - edge0)))
    return t * t * (3.0 - 2.0 * t)


def fmt_u8_array(vals: list[int], indent: str = "        ") -> str:
    lines = []
    for i in range(0, len(vals), 16):
        chunk = ", ".join(f"{v:3d}" for v in vals[i : i + 16])
        lines.append(indent + chunk)
    return ",\n".join(lines)


def build_header() -> str:
    pow08 = [to_u8((i / 255.0) ** 0.8) for i in range(256)]

    hal_entries = []
    for name, low, high, ldiff, gdiff, scat, amp, defr, imp in HALATION_PRESETS:
        exp_alpha = max(0.05, (1.87 - scat / 1.8) / 1.2)
        exp_scat_r = max(0.02, 0.20 * amp)
        mask = [to_u8(1.0 - smoothstep(low, high, i / 255.0)) for i in range(256)]
        contrast = [to_u8(smoothstep(low, 1.0, i / 255.0)) for i in range(256)]
        alpha_pow = [to_u8((i / 255.0) ** exp_alpha) for i in range(256)]
        red_impact = [to_u8((i / 255.0) ** 2.4) for i in range(256)]
        scat_r = [to_u8((i / 255.0) ** exp_scat_r) for i in range(256)]
        scat_g = [to_u8((i / 255.0) ** 0.95) for i in range(256)]
        scat_b = [to_u8((i / 255.0) ** 1.10) for i in range(256)]
        hal_entries.append(
            f"    {{ /* {name} */\n"
            f"        .mask = {{\n{fmt_u8_array(mask)}\n        }},\n"
            f"        .contrast = {{\n{fmt_u8_array(contrast)}\n        }},\n"
            f"        .alpha_pow = {{\n{fmt_u8_array(alpha_pow)}\n        }},\n"
            f"        .red_impact = {{\n{fmt_u8_array(red_impact)}\n        }},\n"
            f"        .scat_r = {{\n{fmt_u8_array(scat_r)}\n        }},\n"
            f"        .scat_g = {{\n{fmt_u8_array(scat_g)}\n        }},\n"
            f"        .scat_b = {{\n{fmt_u8_array(scat_b)}\n        }},\n"
            f"        .local_diff_q8 = {int(round(ldiff * 256.0))}u,\n"
            f"        .global_diff_q8 = {int(round(gdiff * 256.0))}u,\n"
            f"        .scattering_u8 = {to_u8(scat)}u,\n"
            f"        .defringe_u8 = {to_u8(defr)}u,\n"
            f"        .impact_u8 = {to_u8(imp)}u,\n"
            f"        .pad = 0u,\n"
            f"    }}"
        )

    grain_entries = []
    for name, amount, scale, shd, mid, hi, color in GRAIN_PRESETS:
        shd_w = []
        mid_w = []
        hi_w = []
        for i in range(256):
            luma = i / 255.0
            g_shd = math.exp(-0.5 * (luma / 0.2) ** 2)
            g_mid = math.exp(-0.5 * ((luma - 0.5) / 0.2) ** 2)
            g_hi = math.exp(-0.5 * ((luma - 1.0) / 0.2) ** 2)
            shd_w.append(to_u8(shd * amount * 2.0 * g_shd))
            mid_w.append(to_u8(mid * amount * g_mid))
            hi_w.append(to_u8(hi * amount * 2.0 * g_hi))
        eff_scale_q8 = int(round((1.0 + (max(1.0, min(48.0, scale)) - 1.0) * 0.06) * 256.0))
        grain_entries.append(
            f"    {{ /* {name} */\n"
            f"        .shd_w = {{\n{fmt_u8_array(shd_w)}\n        }},\n"
            f"        .mid_w = {{\n{fmt_u8_array(mid_w)}\n        }},\n"
            f"        .hi_w = {{\n{fmt_u8_array(hi_w)}\n        }},\n"
            f"        .color_u8 = {to_u8(color)}u,\n"
            f"        .pad = 0u,\n"
            f"        .eff_scale_q8 = {eff_scale_q8}u,\n"
            f"    }}"
        )

    hal_join = ",\n".join(hal_entries)
    grain_join = ",\n".join(grain_entries)

    return f"""/* Auto-generated by mods/film_sims/film_post_mod/make_luts.py - do not edit by hand. */
#ifndef BIONZ_FILM_POST_LUTS_H
#define BIONZ_FILM_POST_LUTS_H

#include <stdint.h>

typedef struct {{
    uint8_t mask[256];
    uint8_t contrast[256];
    uint8_t alpha_pow[256];
    uint8_t red_impact[256];
    uint8_t scat_r[256];
    uint8_t scat_g[256];
    uint8_t scat_b[256];
    uint16_t local_diff_q8;
    uint16_t global_diff_q8;
    uint8_t scattering_u8;
    uint8_t defringe_u8;
    uint8_t impact_u8;
    uint8_t pad;
}} fp_hal_preset_t;

typedef struct {{
    uint8_t shd_w[256];
    uint8_t mid_w[256];
    uint8_t hi_w[256];
    uint8_t color_u8;
    uint8_t pad;
    uint16_t eff_scale_q8;
}} fp_grain_preset_t;

typedef struct {{
    uint8_t pow08[256];
    fp_hal_preset_t hal[4];
    fp_grain_preset_t grain[4];
}} fp_lut_bank_t;

extern const fp_lut_bank_t fp_rodata_blob;
const fp_lut_bank_t fp_rodata_blob __attribute__((visibility("hidden"))) = {{
    .pow08 = {{
{fmt_u8_array(pow08)}
    }},
    .hal = {{
{hal_join}
    }},
    .grain = {{
{grain_join}
    }},
}};

#endif /* BIONZ_FILM_POST_LUTS_H */
"""


if __name__ == "__main__":
    OUT.write_text(build_header(), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
